def generate_docx(output_path: Path, add_fig_placeholders: bool = True) -> None:
    info = StudentInfo()
    doc = Document()
    setup_page(doc)
    setup_default_style(doc)
    add_page_number(doc.sections[0])

    add_title_page(doc, info)
    add_passport_heading(doc)
    for left, right in passport_content(info):
        add_passport_table(doc, left, right)

    # Implementation report is appended after passport as requested.
    add_implementation_report(doc, info, add_fig_placeholders=add_fig_placeholders)
    add_conclusion(doc, info)
    add_sources(doc)

    output_path.parent.mkdir(parents=True, exist_ok=True)
    doc.save(str(output_path))



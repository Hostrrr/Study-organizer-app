def _cell_para(cell):
    return cell.paragraphs[0] if cell.paragraphs else cell.add_paragraph()


def add_passport_table(doc: Document, left_label: str, right_content: str) -> None:
    table = doc.add_table(rows=1, cols=2)
    table.style = "Table Grid"

    left_cell = table.rows[0].cells[0]
    right_cell = table.rows[0].cells[1]

    p_left = _cell_para(left_cell)
    p_left.paragraph_format.first_line_indent = Cm(0)
    p_left.paragraph_format.line_spacing_rule = WD_LINE_SPACING.SINGLE
    run_left = p_left.add_run(left_label)
    set_run_font(run_left, bold=True, size=12)

    p_right = _cell_para(right_cell)
    p_right.paragraph_format.first_line_indent = Cm(0)
    p_right.paragraph_format.line_spacing_rule = WD_LINE_SPACING.SINGLE
    run_right = p_right.add_run(right_content)
    set_run_font(run_right, size=12)

    doc.add_paragraph()


